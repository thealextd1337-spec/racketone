export function translate(language, key) {
  const dictionary = messages[language] ?? messages.en;
  return dictionary[key] ?? messages.en[key] ?? key;
}

export function categoryLabel(language, category) {
  const keys = { feedback: "categoryFeedback", feature: "categoryFeature", bug: "categoryBug" };
  return translate(language, keys[category] ?? "categoryFeedback");
}

export function statusLabel(language, status) {
  const keys = { new: "statusNew", reviewing: "statusReviewing", planned: "statusPlanned", resolved: "statusResolved", closed: "statusClosed" };
  return translate(language, keys[status] ?? "statusNew");
}

export function priorityLabel(language, priority) {
  const keys = { low: "priorityLow", normal: "priorityNormal", high: "priorityHigh" };
  return translate(language, keys[priority] ?? "priorityNormal");
}

export function accountStatusLabel(language, status) {
  const keys = { onboarding: "accountStatusOnboarding", active: "accountStatusActive", deletion_requested: "accountStatusDeletionRequested", deleting: "accountStatusDeleting" };
  return translate(language, keys[status] ?? "accountStatusActive");
}
