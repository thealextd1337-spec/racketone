-- K3: eigener Status ohne Consent-/Gerätezwang und ohne implizite Rücknahme.
begin;
set local timezone = 'UTC';
select plan(44);
select tests.create_user('k3_new', false);
select tests.create_user('k3_active');
select tests.create_user('k3_other');
select tests.authenticate_as('k3_new');
select is(public.account_deletion_status_v1()->>'contractVersion', '1', 'Statusvertrag versioniert');
select is(public.account_deletion_status_v1()->>'profileStatus', 'onboarding', 'Onboarding ohne Consent lesbar');
select is(public.account_deletion_status_v1()->'requestedAt', 'null'::jsonb, 'Ohne Antrag kein erfundener Zeitpunkt');
select is(public.account_deletion_status_v1()->'earliestPurgeAt', 'null'::jsonb, 'Ohne Antrag keine erfundene Frist');
select is(public.account_deletion_status_v1()->>'canCancel', 'false', 'Ohne Antrag keine Recovery');
select ok((public.account_deletion_status_v1()->>'serverTime')::timestamptz between now() and clock_timestamp(), 'Frische Serverzeit statt Clientuhr');
select public.request_account_deletion();
select is(public.account_deletion_status_v1()->>'profileStatus', 'deletion_requested', 'Antrag sichtbar');
select is((public.account_deletion_status_v1()->>'requestedAt')::timestamptz, now(), 'Tatsächlicher Antrag sichtbar');
select is((public.account_deletion_status_v1()->>'earliestPurgeAt')::timestamptz, now()+interval '14 days', 'Genau 14 Tage');
select is(public.account_deletion_status_v1()->>'canCancel', 'true', 'Onboarding-Rücknahme zulässig');
select public.request_account_deletion();
reset role;
select is((select previous_status from private.consent_deletion_origins where profile_id=tests.uid('k3_new')),
  'onboarding', 'Replay behält Ursprung');
update public.profile_settings set deletion_requested_at=clock_timestamp()-interval '14 days'+interval '1 minute'
  where profile_id=tests.uid('k3_new');
select tests.authenticate_as('k3_new');
select is(public.account_deletion_status_v1()->>'canCancel', 'true', 'Vor 14 Tagen rücknehmbar nach bestehendem RPC-Vertrag');
select public.cancel_account_deletion();
select is(public.account_deletion_status_v1()->>'profileStatus', 'onboarding', 'Recovery bleibt Onboarding');
select is(public.account_deletion_status_v1()->'requestedAt', 'null'::jsonb, 'Rücknahme entfernt Zeitpunkt');
select public.request_account_deletion();
reset role;
update public.profile_settings set deletion_requested_at=now()-interval '14 days' where profile_id=tests.uid('k3_new');
select tests.authenticate_as('k3_new');
select is(public.account_deletion_status_v1()->>'canCancel', 'false', 'An 14 Tagen geschlossen');
select throws_ok('select public.cancel_account_deletion()', 'P0001', 'no_deletion_pending', 'Grenze verweigert Recovery');
select public.request_account_deletion();
select is((public.account_deletion_status_v1()->>'requestedAt')::timestamptz, now()-interval '14 days', 'Replay verschiebt abgelaufene Frist nicht');
select public.my_auth_profile();
select tests.authenticate_as('k3_new');
select is(public.account_deletion_status_v1()->>'profileStatus', 'deletion_requested', 'Lesen und erneutes Login nehmen nichts zurück');
reset role;
update public.profile_settings set deletion_requested_at=now()-interval '15 days' where profile_id=tests.uid('k3_new');
select tests.authenticate_as('k3_new');
select is(public.account_deletion_status_v1()->>'canCancel', 'false', 'Nach 14 Tagen geschlossen');
select throws_ok('select public.cancel_account_deletion()', 'P0001', 'no_deletion_pending', 'Nachfrist verweigert Recovery');
reset role;
update public.profile_settings set deletion_requested_at=now() where profile_id=tests.uid('k3_new');
delete from private.consent_deletion_origins where profile_id=tests.uid('k3_new');
select tests.authenticate_as('k3_new');
select is(public.account_deletion_status_v1()->>'canCancel', 'false', 'Fehlender Marker schließt Recovery');
reset role;
insert into private.consent_deletion_origins values(tests.uid('k3_new'),'onboarding');
update public.profile_settings set deletion_requested_at=null where profile_id=tests.uid('k3_new');
select tests.authenticate_as('k3_new');
select is(public.account_deletion_status_v1()->>'canCancel', 'false', 'Fehlender Zeitpunkt schließt Recovery');
select is(public.account_deletion_status_v1()->'earliestPurgeAt', 'null'::jsonb, 'Kein Fristerfinden bei inkonsistentem Antrag');

-- Aktives Konto mit veralteter Zustimmung und widerrufener Installation behält Kontorechte.
reset role;
select tests.publish_consent_documents('k3-old');
select tests.accept_current_consents(tests.uid('k3_active'));
select tests.publish_consent_documents('k3-new');
select tests.authenticate_as('k3_active');
reset role;
update private.cloud_installations set revoked_at=clock_timestamp() where profile_id=tests.uid('k3_active');
update private.cloud_session_bindings set revoked_at=clock_timestamp() where profile_id=tests.uid('k3_active');
select tests.authenticate_session(tests.uid('k3_active'), (select session_id from tests.account_sessions where profile_id=tests.uid('k3_active')));
select is(public.account_deletion_status_v1()->>'profileStatus', 'active', 'Status unabhängig von Consent und Gerätewiderruf');
select lives_ok('select public.request_account_deletion()', 'Unabhängiger Antrag bleibt bedienbar');
select is(public.account_deletion_status_v1()->>'canCancel', 'true', 'Unabhängige Recovery bleibt bedienbar');
select lives_ok('select public.cancel_account_deletion()', 'Unabhängige Rücknahme ausführbar');
select is(public.account_deletion_status_v1()->>'profileStatus', 'active', 'Aktive Recovery bleibt active');
select throws_ok('select public.cloud_sync_push_v1(''{}'')', '42501', 'consent_required', 'Keine Cloud-Schreibrechte durch K3');
select set_config('tests.k3claims',current_setting('request.jwt.claims'),true);
select set_config('request.jwt.claims',(current_setting('tests.k3claims')::jsonb-'session_id')::text,true);
select throws_ok('select public.account_deletion_status_v1()', '42501', 'cloud_session_changed', 'Fehlende Sitzung geschlossen');
select set_config('request.jwt.claims',jsonb_set(current_setting('tests.k3claims')::jsonb,'{session_id}', '"invalid"')::text,true);
select throws_ok('select public.account_deletion_status_v1()', '42501', 'cloud_session_changed', 'Kaputte Sitzung geschlossen');
select set_config('request.jwt.claims',jsonb_set(current_setting('tests.k3claims')::jsonb,'{session_id}',
  to_jsonb((select session_id from tests.account_sessions where profile_id=tests.uid('k3_other'))))::text,true);
select throws_ok('select public.account_deletion_status_v1()', '42501', 'cloud_session_changed', 'Fremde Sitzung geschlossen');
select set_config('request.jwt.claims',jsonb_set(current_setting('tests.k3claims')::jsonb,'{session_id}',to_jsonb(gen_random_uuid()))::text,true);
select throws_ok('select public.account_deletion_status_v1()', '42501', 'cloud_session_changed', 'Unbekannte Sitzung geschlossen');
select set_config('request.jwt.claims',jsonb_set(current_setting('tests.k3claims')::jsonb,'{exp}','0')::text,true);
select throws_ok('select public.account_deletion_status_v1()', '42501', 'cloud_session_changed', 'Abgelaufenes JWT geschlossen');
select set_config('request.jwt.claims',current_setting('tests.k3claims'),true);
reset role;
update auth.sessions set not_after=clock_timestamp()-interval '1 second' where user_id=tests.uid('k3_active');
select tests.authenticate_session(tests.uid('k3_active'), (select session_id from tests.account_sessions where profile_id=tests.uid('k3_active')));
select throws_ok('select public.account_deletion_status_v1()', '42501', 'cloud_session_changed', 'Abgelaufene Authsitzung geschlossen');
reset role;
delete from auth.sessions where user_id=tests.uid('k3_active');
select tests.authenticate_session(tests.uid('k3_active'), (select session_id from tests.account_sessions where profile_id=tests.uid('k3_active')));
select throws_ok('select public.account_deletion_status_v1()', '42501', 'cloud_session_changed', 'Widerrufene Authsitzung geschlossen');
select throws_ok('select private.run_account_deletion_job_v1()', '42501', null, 'Alltagstoken führt keinen Job aus');
select throws_ok('select public.account_deletion_job_status_v1()', '42501', null, 'Alltagstoken liest keine Betriebsdaten');
reset role;
select ok(not private.has_current_consents(tests.uid('k3_active')), 'Recovery bestätigt keine neue Fassung');
select is((select status from public.profiles where id=tests.uid('k3_other')), 'active', 'Fremder Account unverändert');
select tests.authenticate_anon();
select throws_ok('select public.account_deletion_status_v1()', '42501', null, 'anon liest keinen Status');
select throws_ok('select private.run_account_deletion_job_v1()', '42501', null, 'anon führt keinen Job aus');
select throws_ok('select public.account_deletion_job_status_v1()', '42501', null, 'anon liest keine Betriebsdaten');
reset role;
select ok(not has_table_privilege('authenticated','private.account_deletion_job_state','SELECT'), 'Zustandstabelle nicht direkt lesbar');
select * from finish();
rollback;
