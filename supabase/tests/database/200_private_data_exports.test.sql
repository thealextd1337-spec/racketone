-- K2: unabhängige Kontorechte, Idempotenz, CAS, Ablauf und dauerhafte Cleanup-Tombstones.
begin;
select no_plan();
select tests.world();
select tests.authenticate_as('alice');
select set_config('tests.k2_request','20000000-0000-4000-8000-000000000001',true);
select set_config('tests.k2_res',public.request_data_export_v1(current_setting('tests.k2_request')::uuid)::text,true);
select is(current_setting('tests.k2_res')::jsonb->>'status','pending','ohne Consent reservierbar');
select is(current_setting('tests.k2_res')::jsonb->>'producer','true','erste Anfrage bekommt Produzent');
select ok((current_setting('tests.k2_res')::jsonb->>'objectPath') !~ tests.uid('alice')::text,'zufälliger Pfad ohne Konto-ID');
select is(public.request_data_export_v1(current_setting('tests.k2_request')::uuid)->>'producer',null,'Wiederholung startet keinen zweiten Produzenten');
select is(public.request_data_export_v1('20000000-0000-4000-8000-000000000002')->>'producer',null,'anderer Schlüssel startet keinen zweiten Kontoproduzenten');
select ok(public.data_export_snapshot_v1(current_setting('tests.k2_request')::uuid,(current_setting('tests.k2_res')::jsonb->>'attemptId')::uuid) ? 'data','vollständiger Snapshot ohne Consent');
select is(public.data_export_snapshot_v1(current_setting('tests.k2_request')::uuid,gen_random_uuid())->>'error','export_unavailable','falscher Versuch erhält keine Daten');
select is(public.data_export_status_v1(current_setting('tests.k2_request')::uuid)->>'status','pending','eigener Status');
select throws_ok($$select public.finalize_data_export_v1(gen_random_uuid(),'ready')$$,'42501',null,'Nutzer darf nicht finalisieren');
select throws_ok($$select public.claim_data_export_cleanup_v1()$$,'42501',null,'Nutzer darf nicht aufräumen');
select throws_ok($$select count(*) from private.data_exports$$,'42501',null,'Metadaten privat');
select tests.authenticate_as('bob');
select is(public.data_export_status_v1(current_setting('tests.k2_request')::uuid)->>'error','not_found','fremder Request 404');
select is(public.data_export_status_v1(gen_random_uuid())->>'error','not_found','unbekannter Request gleich');
select is(public.data_export_status_v1(current_setting('tests.k2_request')::uuid,true)->>'error','not_found','fremder Download 404');
reset role;
select ok(exists(select 1 from private.data_export_objects where object_path=current_setting('tests.k2_res')::jsonb->>'objectPath'),'Objekt vor Upload registriert');
update private.data_exports set lease_until=clock_timestamp()-interval '1 second' where owner_id=tests.uid('alice');
select tests.authenticate_as('alice');
select set_config('tests.k2_new',public.request_data_export_v1(current_setting('tests.k2_request')::uuid)::text,true);
select is(current_setting('tests.k2_new')::jsonb->>'producer','true','abgelaufene Lease wird übernommen');
select isnt(current_setting('tests.k2_new')::jsonb->>'attemptId',current_setting('tests.k2_res')::jsonb->>'attemptId','neue Generation');
select isnt(current_setting('tests.k2_new')::jsonb->>'objectPath',current_setting('tests.k2_res')::jsonb->>'objectPath','neuer Objektpfad');
reset role;
set local role service_role;
select is(public.finalize_data_export_v1((current_setting('tests.k2_res')::jsonb->>'attemptId')::uuid,'ready',now(),100,repeat('a',64)),false,'später Altproduzent verliert CAS');
select is(public.finalize_data_export_v1((current_setting('tests.k2_new')::jsonb->>'attemptId')::uuid,'ready',now(),100,repeat('a',64)),true,'aktueller Produzent gewinnt');
select is(public.finalize_data_export_v1((current_setting('tests.k2_new')::jsonb->>'attemptId')::uuid,'ready',now(),100,repeat('b',64)),false,'fertiges Archiv nicht überschreibbar');
reset role;
select tests.authenticate_as('alice');
select is(public.request_data_export_v1(current_setting('tests.k2_request')::uuid)->>'sha256',repeat('a',64),'Retry liefert genau Gewinner');
select is(public.data_export_status_v1(current_setting('tests.k2_request')::uuid,true)->>'objectPath',current_setting('tests.k2_new')::jsonb->>'objectPath','Downloadfreigabe für Gewinner');
reset role;
update public.devices set revoked_at=clock_timestamp() where profile_id=tests.uid('alice');
select tests.authenticate_as('alice');
select is(public.data_export_status_v1(current_setting('tests.k2_request')::uuid)->>'status','ready','Gerätewiderruf sperrt eigene Kontorechte nicht');
reset role;
update auth.sessions set not_after=clock_timestamp()-interval '1 second' where user_id=tests.uid('alice');
select tests.authenticate_as('alice');
select throws_ok($$select public.data_export_status_v1(current_setting('tests.k2_request')::uuid,true)$$,'42501','cloud_session_changed','alte Sitzung nach not_after verweigert');
select throws_ok($$select public.request_data_export_v1(gen_random_uuid())$$,'42501','cloud_session_changed','Anforderung nach Widerruf verweigert');
reset role;
update auth.sessions set not_after=clock_timestamp()+interval '1 hour' where user_id=tests.uid('alice');
update private.data_exports set expires_at=clock_timestamp()-interval '1 second' where owner_id=tests.uid('alice');
update private.data_export_objects set next_cleanup_at=clock_timestamp()-interval '1 second';
select tests.authenticate_as('alice');
select is(public.data_export_status_v1(current_setting('tests.k2_request')::uuid,true)->>'status','expired','Ablauf verhindert Download');
reset role;
set local role service_role;
select is(jsonb_array_length(public.claim_data_export_cleanup_v1()),2,'Gewinner und verlorener Versuch aufräumbar');
select public.ack_data_export_cleanup_v1(array[(current_setting('tests.k2_res')::jsonb->>'objectPath'),(current_setting('tests.k2_new')::jsonb->>'objectPath')]);
select is(jsonb_array_length(public.claim_data_export_cleanup_v1()),0,'bestätigte Löschung pausiert bis Wiedervorlage');
reset role;
select is((select count(*)::int from private.data_export_objects),2,'Tombstones bleiben für späte Uploads erhalten');
update private.data_export_objects set next_cleanup_at=clock_timestamp()-interval '1 second';
set local role service_role;
select is(jsonb_array_length(public.claim_data_export_cleanup_v1()),2,'verspäteter Produzent erneut physisch aufräumbar');
reset role;
select tests.authenticate_as('bob');
select set_config('tests.k2_bob',public.request_data_export_v1('20000000-0000-4000-8000-000000000003')::text,true);
reset role;
select set_config('tests.k2_epoch',(select epoch::text from private.data_export_epoch),true);
select private.purge_account(tests.uid('alice'));
select is((select epoch from private.data_export_epoch),current_setting('tests.k2_epoch')::bigint+1,'Owner-Purge erhöht Epoche');
select ok(exists(select 1 from private.data_export_objects where object_path=current_setting('tests.k2_new')::jsonb->>'objectPath'),'Pfade überleben Besitzerkaskade');
select tests.authenticate_as('bob');
select is(public.data_export_status_v1('20000000-0000-4000-8000-000000000003')->>'status','expired','Mitspieler-Purge invalidiert fremdes Snapshot');
reset role;
set local role service_role;
select is(public.finalize_data_export_v1((current_setting('tests.k2_bob')::jsonb->>'attemptId')::uuid,'ready',now(),100,repeat('b',64)),false,'Purge während Erzeugung verhindert Finalisierung');
select ok(jsonb_array_length(public.claim_data_export_cleanup_v1())>=3,'Purge erfasst alle Objektpfade');
reset role;
select ok(not has_function_privilege('anon','public.request_data_export_v1(uuid)','EXECUTE'),'anon ohne Anforderungsrecht');
select ok(not has_function_privilege('service_role','public.request_data_export_v1(uuid)','EXECUTE'),'kein Owner-Seam für Service');
select ok(not has_function_privilege('authenticated','public.ack_data_export_cleanup_v1(text[])','EXECUTE'),'Cleanup-Ack nur Service');
select * from finish();
rollback;
